#!/usr/bin/env python3
"""Generate zxvision/zxvision_hungarian_table.h from translations/hu.tsv.

hu.tsv columns: english <TAB> hungarian [<TAB> context]. In the texts
\\t, \\n and \\\\ are escapes. Lines starting with # are comments. Rows with
an empty Hungarian text are left out (the English text stays).
"""
import os, sys

here = os.path.dirname(os.path.abspath(__file__))

def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            out.append({'t': '\t', 'n': '\n', '\\': '\\'}.get(n, '\\' + n))
            i += 2
        else:
            out.append(c); i += 1
    return ''.join(out)

def c_string(s):
    b = s.encode('utf-8')
    out = []
    for ch in b:
        if ch == 0x22: out.append('\\"')
        elif ch == 0x5c: out.append('\\\\')
        elif ch == 0x0a: out.append('\\n')
        elif ch == 0x09: out.append('\\t')
        elif 32 <= ch < 127: out.append(chr(ch))
        else: out.append('\\%03o' % ch)
    return '"' + ''.join(out) + '"'

rows = {}
with open(os.path.join(here, 'hu.tsv'), encoding='utf-8') as f:
    for n, line in enumerate(f, 1):
        line = line.rstrip('\n')
        if not line or line.startswith('#'): continue
        cols = line.split('\t')
        if len(cols) < 2: sys.exit('hu.tsv:%d: missing column' % n)
        en, hu = unescape(cols[0]), unescape(cols[1])
        if not hu: continue
        if en in rows and rows[en] != hu:
            sys.exit('hu.tsv:%d: two translations for %r' % (n, en))
        rows[en] = hu

items = sorted(rows.items(), key=lambda kv: kv[0].encode('utf-8'))
out = ['/* Generated by translations/make_table.py from translations/hu.tsv.',
       '   Do not edit. */', '',
       'struct s_hungarian_string {', '    const char *english;', '    const char *hungarian;', '};', '',
       'static const struct s_hungarian_string hungarian_strings[]={']
for en, hu in items:
    out.append('    {%s,%s},' % (c_string(en), c_string(hu)))
if not items:
    out.append('    {"",""},')
out.append('};')
with open(os.path.join(here, '..', 'zxvision', 'zxvision_hungarian_table.h'), 'w') as f:
    f.write('\n'.join(out) + '\n')
print('%d strings' % len(items))
